def test_conditional_enumeration_ordered_paths() -> None:
    plan = Plan(
        alpha=F(1, 2), delta=F(1, 5), batch=2, max_pairs=6, rule=StakeRule("mixture", CANDIDATES[1])
    )
    losses = [F(2, 3), F(0), F(1, 5), F(1), F(1, 2), F(1, 4)]
    boundaries = dict(make_boundary((plan, n)) for n in (2, 4, 6))
    expected = dict.fromkeys(("PASS", "BLOCK", "INCONCLUSIVE"), F(0))
    for path in itertools.product((-1, 0), repeat=6):
        mass = math.prod(q if d == -1 else 1 - q for d, q in zip(path, losses, strict=True))
        result = decide(
            path,
            alpha=plan.alpha,
            delta=plan.delta,
            batch=plan.batch,
            max_pairs=plan.max_pairs,
            rule=plan.rule,
        )
        assert result.verdict != "ERROR"
        expected[result.verdict] += mass
    assert binary_enumeration(losses, plan, boundaries) == expected


def test_coverage_exact() -> None:
    for row in coverage():
        cells, pairs = int(row["cells"]), int(row["pairs"])
        probability = F(str(row["probability_exact"]))
        assert probability == F(cells - 1, cells) ** pairs
        assert F(str(row["expected_exact"])) == cells * probability


