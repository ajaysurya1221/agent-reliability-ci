@pytest.mark.parametrize("key,index,cells,expected,seed", GOLDEN)
def test_golden(key: str, index: int, cells: int, expected: int, seed: int) -> None:
    assert cell_index(bytes.fromhex(key), index, cells) == expected
    assert trial_seed(bytes.fromhex(key), index) == seed


def test_key_canonical_and_bound() -> None:
    plan = plan_for(1)
    cells = [
        {"task_id": "b", "condition_id": "c", "label": "cosmetic"},
        {"task_id": "a", "condition_id": "c"},
    ]
    key = schedule_key(cells, "A", "B", plan)
    reordered = [
        {"condition_id": "c", "task_id": "a", "label": "new"},
        {"condition_id": "c", "task_id": "b"},
    ]
    assert schedule_key(reordered, "A", "B", plan) == key
    assert (
        schedule_key(
            cells,
            "A",
            "B",
            replace(plan, rule=StakeRule("mixture", tuple(reversed(plan.rule.fractions)))),
        )
        == key
    )
    assert schedule_key(cells, "A", "B", plan, ["prior"]) != key
    content = [dict(cells[0], oracle_sha256="a" * 64), cells[1]]
    assert schedule_key(content, "A", "B", plan) != key
    changed = [dict(content[0], oracle_sha256="b" * 64), cells[1]]
    assert schedule_key(changed, "A", "B", plan) != schedule_key(content, "A", "B", plan)
    assert schedule_key(cells, "A", "different", plan) != key
    assert schedule_key(cells, "different", "B", plan) != key
    for other in (
        replace(plan, alpha=F(1, 10)),
        replace(plan, delta=F(1, 5)),
        replace(plan, batch=1),
        replace(plan, max_pairs=399),
        plan_for(0),
    ):
        assert schedule_key(cells, "A", "B", other) != key
    assert schedule_key([{"task_id": "c", "condition_id": "c"}], "A", "B", plan) != key
    assert schedule_key(
        [{"task_id": "task-a", "condition_id": "clean"}], "baseline-sha", "candidate-sha", plan
    ).hex() == ("2666deade823461355002528fb424bf93d60d547378b42e9ed5ec3da74def9d8")
    with pytest.raises(ValueError):
        schedule_key(cells * 2, "A", "B", plan)


@pytest.mark.parametrize("cells", [7, 20, 60, 150])
def test_uniformity(cells: int) -> None:
    key = hashlib.sha256(b"S1b uniformity declared key").digest()
    counts = [0] * cells
    for i in range(200_000):
        counts[cell_index(key, i, cells)] += 1
    expected = 200_000 / cells
    statistic = sum((c - expected) ** 2 / expected for c in counts)
    # Conservative chi-square upper-tail diagnostic, x=log(1e6), fixed in advance.
    # This is not proof of hash IID behavior; the finite test detects gross bias.
    df, x = cells - 1, math.log(1_000_000)
    assert statistic < df + 2 * math.sqrt(df * x) + 2 * x


def test_rejection_branch() -> None:
    attempts: list[int] = []

    def draw(a: int) -> int:
        attempts.append(a)
        return (15, 14, 13)[a]

    assert rejection_index(draw, 7, bits=4) == 6
    assert attempts == [0, 1, 2]
    with pytest.raises(ValueError):
        rejection_index(draw, 17, bits=4)


def test_repeated_cell_seeds() -> None:
    key = bytes(32)
    indices = [i for i in range(400) if cell_index(key, i, 20) == 0]
    seeds = [trial_seed(key, i) for i in indices]
    assert len(indices) > 1 and len(seeds) == len(set(seeds))
    assert all(0 <= seed < 2**63 for seed in seeds)
    for index in (-1, 2**64):
        with pytest.raises(ValueError):
            cell_index(key, index, 20)


def test_floors_and_terminal_partial() -> None:
    plan = plan_for(1)
    floors = decision_floors(plan)
    assert floors == {
        "earliest_possible_pass": 10,
        "all_zero_pass": 80,
        "pass_with_losses_and_zeros": {"1": 100, "2": 110, "3": 120, "5": 150},
        "earliest_block": 20,
        "max_losses_with_zeros": {"200": 8, "400": 23},
        "max_losses_with_wins": {"200": 88, "400": 184},
    }
    for delta in (F(1, 20), F(1, 10), F(1, 5)):
        for batch in (1, 10):
            p = replace(plan, delta=delta, batch=batch)
            validate_plan(p)
            result = decide(
                [0] * 400,
                alpha=p.alpha,
                delta=p.delta,
                rule=p.rule,
                batch=p.batch,
                max_pairs=p.max_pairs,
            )
            assert result.stopping_pairs == decision_floors(p)["all_zero_pass"]
    with pytest.raises(ValueError, match="all-zero PASS floor"):
        validate_plan(replace(plan, max_pairs=60))
    partial = replace(plan, max_pairs=81)
    validate_plan(partial)
    assert partial.checkpoint(81)
    assert decision_floors(replace(plan, max_pairs=9))["earliest_possible_pass"] == 9


def test_frontier_every_default_checkpoint() -> None:
    plan = plan_for(1)
    for n in range(10, 401, 10):
        _, boundary = make_boundary((plan, n))
        for m, (passed, blocked) in enumerate(boundary):
            for p in {0, n - m, passed - 1, passed, blocked, blocked + 1}:
                if 0 <= p <= n - m:
                    assert boundary_verdict(boundary, m, p) == classify(
                        *count_wealth(n, m, p, plan), plan.alpha
                    ), (n, m, p)


