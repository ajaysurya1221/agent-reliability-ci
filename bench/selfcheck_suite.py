Law = tuple[F, F, F]


def _manifest(n: int, rounds: int, **rule: object) -> SuiteManifest:
    return create_suite_manifest(
        suite_id="bench",
        tasks=tuple({"task_id": f"t{i}"} for i in range(n)),
        conditions=({"condition_id": "clean"},),
        toolset="fixtures:tools",
        contract={"oracle": "fixtures:oracle"},
        baseline={"label": "a", "agent": "fixtures:a"},
        candidate={"label": "b", "agent": "fixtures:b"},
        max_rounds=rounds,
        acknowledge_single_round=rounds == 1,
        max_errored_pairs=rule.pop("max_errored_pairs", 0),
        **rule,
    )


def default_rule(n: int, rounds: int | None = None) -> SuiteRule:
    # Literal defaults could drift from the manifest while every old check passed.
    return rule_of(_manifest(n, default_max_rounds(n) if rounds is None else rounds))


def joint_law(a: F, b: F, coupling: str) -> Law:
    """Bernoulli joint law at independence or a Frechet coupling endpoint."""
    if coupling == "positive":
        both = min(a, b)
    elif coupling == "negative":
        both = max(F(0), a + b - 1)
    elif coupling == "independent":
        both = a * b
    else:
        raise ValueError("unknown coupling")
    return a - both, 1 - a - b + 2 * both, b - both


def calibration_cases(n: int, quick: bool = False) -> list[tuple[str, tuple[Law, ...]]]:
    cases: list[tuple[str, tuple[Law, ...]]] = []
    offsets = (F(0),) if quick else (F(-1, 100), F(0), F(1, 100))
    for offset in offsets:
        mean = F(-1, 10) + offset
        for coupling in ("positive", "independent", "negative"):
            law = joint_law(F(11, 20), F(9, 20) + offset, coupling)
            cases.append((f"homogeneous/{coupling}/{offset}", (law,) * n))
        if n > 1:
            # Half the cells are far below the margin, the rest compensate.
            low_count = n // 2
            low = F(-7, 10) + offset
            high = (n * mean - low_count * low) / (n - low_count)
            for coupling in ("positive", "negative"):
                laws = tuple(
                    joint_law((1 - d) / 2, (1 + d) / 2, coupling)
                    for d in (low,) * low_count + (high,) * (n - low_count)
                )
                cases.append((f"heterogeneous/{coupling}/{offset}", laws))
    # Coupling endpoints at a fixed arm rate do not span the three-point margin
    # family: the old grid could never reproduce the ADR's tightest search rows.
    zeros = (F(1, 10),) if quick else (*(F(i, 10) for i in range(10)), F(1, 9), F(9, 20))
    delta = default_rule(n).delta
    for p_zero in zeros:
        law = ((1 - p_zero + delta) / 2, p_zero, (1 - p_zero - delta) / 2)
        cases.append((f"three-point/p0/{p_zero}", (law,) * n))
    return cases


# Rounded percentages transcribed from ADR 0011's boundary-maxima row
# (2026-11-11), sourced there to the S1c review search, not Table C.
# Kept here so the comparison and its provenance ship on this branch.
ADR_MARGIN_PERCENT = {
    1: F(216, 100),
    2: F(197, 100),
    5: F(167, 100),
    10: F(142, 100),
    20: F(115, 100),
}


def check_calibration(quick: bool = False) -> dict[int, tuple[F, F]]:
    print("\nDirectional errors (each asserted <= alpha/2; only its null is tested)")
    print("| cells | law | false PASS | false BLOCK |")
    print("|---:|---|---:|---:|")
    maxima: dict[int, tuple[F, F]] = {}
    for n in (1, 2) if quick else (1, 2, 5, 10, 20):
        rule = default_rule(n, (80 + n - 1) // n if quick else None)
        worst_pass, worst_block = F(0), F(0)
        for name, laws in calibration_cases(n, quick):
            mean = sum((p - m for m, _, p in laws), F(0)) / n
            result = operating_characteristics(laws, rule)
            fp = result.p_pass if mean <= -rule.delta else None
            fb = result.p_block if mean >= -rule.delta else None
            assert result.p_pass + result.p_block + result.p_inconclusive == 1
            if fp is not None:
                assert fp <= rule.alpha / 2, (n, name, "false PASS", fp)
                worst_pass = max(worst_pass, fp)
            if fb is not None:
                assert fb <= rule.alpha / 2, (n, name, "false BLOCK", fb)
                worst_block = max(worst_block, fb)
            print(f"| {n} | {name} | {_decimal(fp)} | {_decimal(fb)} |", flush=True)
        maxima[n] = worst_pass, worst_block
    print("\nLargest observed directional errors per grid (this finite grid only)")
    print("| cells | false PASS | false BLOCK |")
    print("|---:|---:|---:|")
    for n, (fp, fb) in maxima.items():
        print(f"| {n} | {_decimal(fp)} | {_decimal(fb)} |")
    if not quick:
        print("ADR margin comparison: exact difference in percentage points from rounded source")
        for n, (fp, fb) in maxima.items():
            observed = 100 * max(fp, fb)
            reference = ADR_MARGIN_PERCENT[n]
            difference = observed - reference
            # Exact fraction, even when the rounded percentage reproduces the ADR.
            print(
                f"cells={n}: observed={float(observed):.6f}%; ADR={float(reference):.2f}%; "
                f"exact difference={difference}",
                flush=True,
            )
    return maxima


def _decimal(value: F | None) -> str:
    return "outside null" if value is None else f"{float(value):.9f}"


